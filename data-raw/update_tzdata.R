# Refreshes inst/include/cppally/time/tzdata.h from the latest IANA time zone database release.

tzdata_files <- c(
  "africa", "antarctica", "asia", "australasia", "backward", "etcetera",
  "europe", "northamerica", "southamerica"
)

# Joins the IANA source files in `src` into one zic input text, dropping comments and blank lines
read_tzdata <- function(src) {
  version <- readLines(file.path(src, "version"), n = 1)
  lines <- unlist(lapply(file.path(src, tzdata_files), readLines, encoding = "UTF-8"))
  lines <- sub("[[:space:]]*#.*$", "", lines) # Remove comments
  lines <- gsub("[[:space:]]+", "\t", lines) # Collapse spaces/tabs into single tab
  lines <- sub("\t$", "", lines) # Remove trailing tab
  lines <- lines[nzchar(lines)] # Remove empty lines

  # error on non-ASCII
  if (any(grepl("[^\x01-\x7f]", lines, useBytes = TRUE))) {
    stop("Non-ASCII characters left in the time zone data")
  }
  # First line "# version 2026d", like IANA's own tzdata.zi
  c(paste("# version", version), lines)
}

# Puts zones and links in name order so that tz.h doesn't need to sort them.
# A link's name is its alias, the last field, not its target.
# Rules are grouped by name, keeping file order within a name, so tz.h's insertion sort has little to do.
# Strings are sorted using `order(method = "radix")`
# which means the sorting is done on bytes in C locale (matching std::string).
sort_tzdata <- function(lines) {
  version <- lines[1]
  lines <- lines[-1]
  fields <- strsplit(lines, "\t", fixed = TRUE)
  first <- vapply(fields, `[`, character(1), 1)
  is_head <- nzchar(first) # Zone continuation lines start with a tab
  entry <- cumsum(is_head) # Entry number of each line, a Zone's continuation lines share its entry
  entries <- split(lines, entry) # One element per entry
  types <- first[is_head]
  entry_fields <- fields[is_head]

  if (!all(types %in% c("Rule", "Zone", "Link"))) {
    stop("Unexpected line type in the time zone data: ", paste(setdiff(types, c("Rule", "Zone", "Link")), collapse = ", "))
  }

  keys <- vapply(entry_fields, \(f) switch(f[1], Rule = f[2], Zone = f[2], Link = f[3]), character(1))

  zones <- which(types == "Zone")
  links <- which(types == "Link")
  rules <- which(types == "Rule")

  # tz.h follows at most one link, straight to a zone
  targets <- vapply(entry_fields[links], `[`, character(1), 2)
  if (!all(targets %in% keys[zones]) || any(keys[links] %in% keys[zones])) {
    stop("Links must point directly at zones, with no link-to-link chains or names shared with zones")
  }

  # Entries in name order, order() is stable so rules sharing a name stay in file order
  rules_order <- rules[order(keys[rules], method = "radix")]
  zones_order <- zones[order(keys[zones], method = "radix")]
  links_order <- links[order(keys[links], method = "radix")]
  # Rules, then zones, then links
  entry_order <- c(rules_order, zones_order, links_order)
  c(version, unlist(entries[entry_order], use.names = FALSE))
}

# Embeds lines in a C++ header as raw deflate data (RFC 1951), inflated by puff.h
write_tzdata_header <- function(lines,
                                dest = file.path("inst", "include", "cppally", "time", "tzdata.h"),
                                chars_per_line = 100) {
  version <- sub("^# version ", "", lines[1])
  text <- charToRaw(paste0(lines, "\n", collapse = ""))
  zlib <- memCompress(text, type = "gzip")
  # memCompress()'s "gzip" is a zlib stream (RFC 1950): a 2-byte header without a preset dictionary, then raw deflate,
  # then a 4-byte Adler-32 checksum
  header_bytes <- as.integer(zlib[1:2])
  if (header_bytes[1] != 0x78 || (header_bytes[1] * 256 + header_bytes[2]) %% 31 != 0 || bitwAnd(header_bytes[2], 0x20) != 0) {
    stop("memCompress() did not return a zlib stream")
  }
  deflated <- zlib[3:(length(zlib) - 4)]
  # Printable ASCII as itself, every other byte (and " \ ?) as a 3-digit octal escape, which can't absorb a following digit
  bytes <- as.integer(deflated)
  tokens <- sprintf("\\%03o", bytes)
  plain <- bytes >= 0x20 & bytes <= 0x7e & !bytes %in% c(0x22, 0x3f, 0x5c)
  tokens[plain] <- intToUtf8(bytes[plain], multiple = TRUE)
  rows <- vapply(split(tokens, (cumsum(nchar(tokens)) - 1) %/% chars_per_line), paste, character(1), collapse = "")
  header <- c(
    "// Generated by data-raw/update_tzdata.R: do not edit by hand",
    paste0("// IANA time zone database ", version, " (https://www.iana.org/time-zones), public domain."),
    "// zic input: the IANA source files joined, comments and blank lines removed, zones and links sorted, then deflated.",
    "",
    "#ifndef CPPALLY_TZDATA_H",
    "#define CPPALLY_TZDATA_H",
    "",
    "#include <cstddef>",
    "",
    "namespace cppally {",
    "",
    "namespace internal {",
    "",
    "namespace tz {",
    "",
    "// Not inline: internal linkage keeps one copy per package, never merged across DLLs",
    paste0("constexpr std::size_t tzdata_size = ", length(text), "; // Inflated size in bytes"),
    "// tzdata as a compressed string literal, inflated by zone_registry::ensure_db()",
    "constexpr unsigned char tzdata_deflated[] =",
    paste0("  \"", rows, "\"", c(rep("", length(rows) - 1), ";")),
    "",
    "}",
    "",
    "}",
    "",
    "}",
    "",
    "#endif"
  )
  con <- file(dest, "wb")
  on.exit(close(con), add = TRUE)
  writeLines(header, con, sep = "\n", useBytes = TRUE)
  message(dest, " updated to IANA ", version, " (", length(text), " bytes deflated to ", length(deflated), ")")
}

update_tzdata <- function() {
  tmp <- tempfile()
  dir.create(tmp)
  on.exit(unlink(tmp, recursive = TRUE), add = TRUE)

  tarball <- file.path(tmp, "tzdata-latest.tar.gz")
  utils::download.file(
    "https://data.iana.org/time-zones/tzdata-latest.tar.gz", tarball, mode = "wb"
  )
  utils::untar(tarball, files = c(tzdata_files, "version"), exdir = tmp)
  write_tzdata_header(sort_tzdata(read_tzdata(tmp)))
}

