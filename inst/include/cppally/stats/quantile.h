// A C++ implementation of R's `stats::quantile.default`.
// Supports quantile methods of type 6, 7, and 8.
// There are three overloads.
// Overload 1 - Accepts a scalar prob and returns a scalar quantile.
// Overload 2 - Accepts a vector of probs and returns a vector of quantiles.
// Overload 3 - Accepts a vector of probs and a 0-indexed permutation vector that sorts the data (with NAs last), 
// generated by `cppally::order()`. This is useful in the case that you already have the order vector 
// hence can avoid the performance cost of the first 2 overloads, which either partition the data, or 
// calculate the full order permutation (if n probs >= some threshold). In the vast majority of cases, the first two 
// overloads are adequate performance-wise.
// 
// License: MIT
// Author: Nick Christofides

