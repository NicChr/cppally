// Use this overload if you have already generated an order permutation vector using `cppally::order()`
template <string_literal Method = "linear", RNumber T>
inline r_vec<r_dbl> quantile(const r_vec<T>& x, const r_vec<r_dbl>& probs, const r_vec<r_int>& order, bool na_rm = false, bool names = true, bool check_order = true){
    
    r_size_t n = x.length();
    r_size_t n_probs = probs.length();
    internal::quantile_impl::check_all_valid_probs(probs);

    if (order.length() != n) [[unlikely]] {
        abort("`quantile()`: `x.length()` must equal `order.length()`");
    }

    if (check_order){
        bool bad_index = false;
        // Check the order permutation elements are valid
        for (r_size_t i = 0; i < n; ++i){
            int idx = order.get(i);
            bad_index |= static_cast<unsigned>(idx) >= static_cast<unsigned>(n);
        }
        if (bad_index) [[unlikely]] {
            abort("`quantile()`: Invalid permutation index, indices must be in [0, n)");
        }
    }

    // Count NAs but assuming they are at the end of sorted vector
    r_size_t i = n;
    while (i > 0 && is_na(x.get(unwrap(order.get(i - 1))))){
        --i;
    }
    r_size_t n_na = n - i;

    r_size_t n_ok = n - n_na;
    r_vec<r_dbl> out(n_probs, na<r_dbl>());

    if (names){
        out.set_names(internal::quantile_impl::quantile_names(probs));
    }

    if (!na_rm && n_na > 0){
        return out;
    }

    auto* x_data = x.data();

    for (r_size_t i = 0; i < n_probs; ++i){
        r_dbl prob = probs.get(i);
        r_dbl q = internal::quantile_impl::do_quantile<Method>(x_data, n_ok, unwrap(prob), &order);
        out.set(i, q);
    }
    return out;
}

template <string_literal Method = "linear", RNumber T>
inline r_dbl quantile(const r_vec<T>& x, double prob, bool na_rm = false){

    internal::quantile_impl::check_valid_prob(prob);

    const r_size_t n = x.length();

    if (is_sorted(x)){
        // NAs are at the tail end of the vector if they exist
        const r_size_t n_na = internal::quantile_impl::sorted_na_count(x);
        if ((n_na > 0 && !na_rm) || n_na == n){
            return na<r_dbl>();
        }
        return internal::quantile_impl::do_quantile<Method>(x.data(), n - n_na, unwrap(prob));
    }

    if constexpr (RIntegerNumber<T>){
        return quantile<Method>(x, r_vec<r_dbl>( {r_dbl(prob)} ), order(x), na_rm, /*names = */ false, /*check_order = */ false).get(0);
    }

    const r_size_t n_na = x.na_count();

    if (n_na > 0 && !na_rm){
        return na<r_dbl>();
    }

    const auto* x_data = x.data();
    std::vector<unwrap_t<T>> v(x_data, x_data + n);

    if (n_na > 0){
        internal::quantile_impl::move_nas_to_end(v.data(), n);
    }

    const double p = unwrap(prob);
    double q;
    internal::quantile_impl::do_quantiles<Method>(v.data(), n - n_na, &p, 1, &q);
    return r_dbl(q);
}

template <string_literal Method = "linear", RNumber T>
inline r_vec<r_dbl> quantile(const r_vec<T>& x, const r_vec<r_dbl>& probs, bool na_rm = false, bool names = true){

    const r_size_t n = x.length();

    const r_size_t n_probs = probs.length();
    internal::quantile_impl::check_all_valid_probs(probs);
    r_vec<r_dbl> out(n_probs, na<r_dbl>());
    r_vec<r_str> quantile_nms(r_null);

    if (names){
        quantile_nms = internal::quantile_impl::quantile_names(probs);
        out.set_names(quantile_nms);
    }

    if (n_probs == 0){
        return out;
    }

    if (n_probs == 1){
        r_dbl q = quantile<Method>(x, probs.get(0), na_rm);
        out.set(0, q);
        return out;
    }

    // integer-based `order()` is very fast, so lower threshold for that
    constexpr int order_method_threshold = RIntegerType<T> ? 2 : 25;

    if (is_sorted(x)){

        const r_size_t n_na = internal::quantile_impl::sorted_na_count(x);

        if ((n_na > 0 && !na_rm) || n_na == n){
            return out;
        }

        const r_size_t n_ok = n - n_na;

        auto* x_data = x.data();
        for (r_size_t i = 0; i < n_probs; ++i){
            const r_dbl p = probs.get(i);
            out.set(i, internal::quantile_impl::do_quantile<Method>(x_data, n_ok, unwrap(p)));
        }

    } else if (n_probs < order_method_threshold) {

        // Use multi-partitioning via nth_elements()

        const r_size_t n_na = x.na_count();
    
        if ((n_na > 0 && !na_rm) || n_na == n){
            return out;
        }

        const r_size_t n_ok = n - n_na;

        std::vector<unwrap_t<T>> v(x.data(), x.data() + n);

        // Move NAs to the end of the vector
        if (n_na > 0){
            internal::quantile_impl::move_nas_to_end(v.data(), n);
        }

        internal::quantile_impl::do_quantiles<Method>(v.data(), n_ok, probs.data(), n_probs, out.data());
    } else {
        // If number of probs is high, it's faster to compute full order permutation
        // and re-use it for repeated quantile estimation
        r_vec<r_dbl> quantiles = quantile<Method>(x, probs, order(x), na_rm, /*names = */ false, /*check_order = */ false);
        quantiles.set_names(quantile_nms);
        return quantiles;
    }
    return out;
}

